"""Run scenarios A-D in every dialing mode and write tables, JSON and charts.

Usage:
    python scripts/run_simulation.py                  # all scenarios, all modes
    python scripts/run_simulation.py --scenarios A B --duration 1200
    python scripts/run_simulation.py --epsilon 0.02 --seed 7

Every number in results/ is produced by actually running the simulator.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.models.campaign import DialMode  # noqa: E402
from app.simulation.charts import generate_charts, label  # noqa: E402
from app.simulation.metrics import SimulationResult  # noqa: E402
from app.simulation.scenarios import SCENARIOS  # noqa: E402
from app.simulation.simulator import run_scenario  # noqa: E402

MODES = [(DialMode.PROGRESSIVE, "STRICT"), (DialMode.PREDICTIVE, "STRICT"), (DialMode.PREDICTIVE, "BOUNDED_RISK")]


def table(results: list[SimulationResult]) -> str:
    cols = [
        ("Scn", lambda r: r.scenario), ("Mode", label), ("Agents", lambda r: r.total_agents),
        ("Avg idle", lambda r: r.avg_available_agents), ("Initiated", lambda r: r.calls_initiated),
        ("Answered", lambda r: r.calls_answered), ("Connected", lambda r: r.calls_connected),
        ("Completed", lambda r: r.calls_completed), ("Failed", lambda r: r.calls_failed),
        ("Cancelled", lambda r: r.calls_cancelled), ("Util %", lambda r: r.agent_utilisation_pct),
        ("Occ %", lambda r: r.occupancy_pct), ("Wait/connect s", lambda r: r.avg_agent_wait_per_connect_s),
        ("Connects/agent-h", lambda r: r.connects_per_agent_hour),
        ("Latency ms (A/B)", lambda r: "/".join(str(r.avg_setup_latency_ms.get(p, "-"))
                                                for p in ("provider_a", "provider_b"))),
        ("Abandoned", lambda r: r.abandoned_calls), ("Dup events", lambda r: r.duplicate_events),
        ("Rejected req", lambda r: r.rejected_requests),
        ("Decisions A/R/F/X", lambda r: "/".join(str(r.safety_decisions.get(k, 0)) for k in
                                                 ("APPROVED", "REDUCED", "FALLBACK_TO_PROGRESSIVE", "REJECTED"))),
        ("Cap. cancels", lambda r: r.capacity_cancellations), ("CB opens", lambda r: r.circuit_openings),
    ]
    lines = ["| " + " | ".join(c for c, _ in cols) + " |", "|" + "---|" * len(cols)]
    for r in results:
        lines.append("| " + " | ".join(str(f(r)) for _, f in cols) + " |")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--scenarios", nargs="+", default=list(SCENARIOS))
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--epsilon", type=float, default=0.01, help="abandon-risk budget for BOUNDED_RISK")
    ap.add_argument("--duration", type=float, default=None, help="override scenario duration (seconds)")
    ap.add_argument("--out", default=str(ROOT / "results"))
    args = ap.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    results: list[SimulationResult] = []
    for key in args.scenarios:
        sc = SCENARIOS[key]
        for mode, safety in MODES:
            r = run_scenario(sc, mode, safety, seed=args.seed, epsilon=args.epsilon,
                             duration_override=args.duration)
            results.append(r)
            print(f"[{key}] {label(r):<24} util={r.agent_utilisation_pct:6.2f}%  connected={r.calls_connected:5d}  "
                  f"abandoned={r.abandoned_calls}  decisions={r.safety_decisions}  ({r.wall_time_s}s wall)",
                  flush=True)

    md = [f"# Simulation results (seed={args.seed}, epsilon={args.epsilon})", "",
          "Generated by `python scripts/run_simulation.py`. Do not edit by hand.", "",
          "Utilisation = time CONNECTED / (AVAILABLE+RESERVED+DIALING+CONNECTED+WRAP_UP) time, "
          "sampled every 1s of virtual time. Occupancy also counts WRAP_UP.", "",
          table(results), ""]
    for sc_key in args.scenarios:
        md += [f"**Scenario {sc_key}**: {SCENARIOS[sc_key].description}", ""]
    (out / "simulation_results.md").write_text("\n".join(md), encoding="utf-8")
    (out / "simulation_results.json").write_text(
        json.dumps([r.as_dict(include_timeline=True) for r in results], indent=1, default=str), encoding="utf-8")
    charts = generate_charts(results, out)
    print("\n" + table(results))
    print(f"\nWrote {out / 'simulation_results.md'}, {out / 'simulation_results.json'} and "
          f"{len(charts)} charts to {out}")


if __name__ == "__main__":
    main()
